#!/bin/sh
# Columbia — regenerate core/gnc/MissionPads.cpp from mission erasable images.
#
# Usage: tools/gen_mission_pads.sh VIRTUAL_AGC_DIR SCENARIO_DIR > core/gnc/MissionPads.cpp
#   VIRTUAL_AGC_DIR  checkout of github.com/virtualagc/virtualagc (for the
#                    ERASABLE_ASSIGNMENTS listings)
#   SCENARIO_DIR     "Apollo - Mission Scenarios" folder of NASSP (Orbiter
#                    Project Apollo), whose scenarios carry the CMC and LGC
#                    erasable images the crews flew with
set -e
V=${1:?virtualagc dir}
S=${2:?scenario dir}
X="python3 $(dirname "$0")/extract_padloads.py"
R=$(dirname "$0")/../rope/sym

cat <<'EOF'
// Columbia — Apollo flight simulator for Haiku
// Copyright (c) 2026 Bryan Irvine. MIT License (see LICENSE).
//
// GENERATED by tools/gen_mission_pads.sh — do not edit.
//
// Pad-loaded erasables of the CMC and LGC for Apollo 7-12: the mission
// constants loaded before flight (TVC and RCS DAP data, SPS flow and
// impulse, entry L/D, landing-radar weights, descent targets, abort
// coefficients ...). Values are mission data from the erasable images in
// the NASSP project's mission scenarios, which reconstruct them from NASA
// documentation; names and sizes come from each program's own
// ERASABLE_ASSIGNMENTS listing.

#include "MissionPads.h"

namespace gnc {

EOF

one() { # name program scenario ship [checks]
	n=$1; p=$2; f=$3; s=$4; shift 4
	$X --erasable "$V/$p/ERASABLE_ASSIGNMENTS.agc" --sym "$R/$p.sym" \
		--scenario "$S/$f" --ship "$s" --name "$n" "$@"
	echo
}

one Apollo7_CMC Colossus237 "Apollo 7/Apollo 7 - 07 - SPS-3 T-15m.scn" "AS-205:" --check ESTROKER=00005
one Apollo8_CMC Colossus237 "Apollo 8/Apollo 8 - 07 - LOI-1 T-15m.scn" "AS-503:" --check ESTROKER=00005
one Apollo9_CMC Colossus249 "Apollo 9/Apollo 9 - 04 - SPS-1 T-15m.scn" "Gumdrop:"
one Apollo9_LGC Sundance306ish "Apollo 9/Apollo 9 - 06 - Docked DPS T-2m.scn" "Spider:"
one Apollo10_CMC Comanche045 "Apollo 10/Apollo 10 - 06 - LOI-1 T-15m.scn" "Charlie-Brown:"
one Apollo10_LGC LUM69R2 "Apollo 10/Apollo 10 - 09 - DOI T-15m.scn" "Snoopy:" --check LRALPHA=01042
one Apollo11_CMC Comanche055 "Apollo 11/Apollo 11 - 06 - LOI-1 T-15m.scn" "Columbia:"
one Apollo11_LGC Luminary099 "Apollo 11/Apollo 11 - 10 - PDI T-15m.scn" "Eagle:" --check LRALPHA=01042
one Apollo12_CMC Comanche067 "Apollo 12/Apollo 12 - 06 - LOI-1 T-15m.scn" "Yankee-Clipper:"
one Apollo12_LGC Luminary116 "Apollo 12/Apollo 12 - 10 - PDI T-15m.scn" "Intrepid:" --check LRALPHA=01042

cat <<'EOF'
const PadWord*
MissionPads(int mission, bool lm)
{
	switch (mission) {
		case 7: return lm ? nullptr : kApollo7_CMC;
		case 8: return lm ? nullptr : kApollo8_CMC;
		case 9: return lm ? kApollo9_LGC : kApollo9_CMC;
		case 10: return lm ? kApollo10_LGC : kApollo10_CMC;
		case 11: return lm ? kApollo11_LGC : kApollo11_CMC;
		default:
			// Apollo 12's loads stand in for the later missions, applied by
			// name to their programs (layouts differ, names mostly don't).
			return lm ? kApollo12_LGC : kApollo12_CMC;
	}
}

}  // namespace gnc
EOF
